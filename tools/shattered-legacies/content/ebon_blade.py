"""The Knights of the Ebon Blade: four death knight heroes and Acherus (0.80.0, hand-made).

Usage (repo root):  python3 tools/shattered-legacies/content/ebon_blade.py
Writes mapdata/WarcraftLegacies/UnitData/UZe1..UZe4.json (heroes, base Udea) and uZe0.json (Acherus: The Ebon Hold,
base WL's Altar of Darkness uaod -- revives them, trains nothing else, indestructible by code) and
src/WarcraftLegacies.Shared/ShatteredLegacies/FactionObjectLimits/EbonBladeObjectInfo.cs.
A hero-only faction (maintainer): every hero has its own skill set -- stock / WL hero skills, no new spells:
  UZe1 Thassarian           frost   Frost Nova, Frost Armor, Death Coil; ult Death and Decay
  UZe2 Koltira Deathweaver  unholy  Carrion Beetles, Animate Dead, Death Pact; ult Locust Swarm
  UZe3 Nazgrim              blood   Critical Strike, Shockwave, Vampiric Aura; ult Bladestorm
  UZe4 Thoras Trollbane     plate   Storm Bolt, Thunder Clap, Endurance Aura; ult Avatar
No Darion Mograine (maintainer: the Mograine name belongs to Lordaeron's Ashbringer), no Rivendare (WL's Scourge).
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
MAP = os.path.join(ROOT, "mapdata", "WarcraftLegacies")
BTN = "ReplaceableTextures\\CommandButtons\\"
INFO = os.path.join(ROOT, "src", "WarcraftLegacies.Shared", "ShatteredLegacies", "FactionObjectLimits",
                    "EbonBladeObjectInfo.cs")


def s(fid, value):
    return {"Id": fid, "Type": 3, "Value": value}


def n(fid, value):
    return {"Id": fid, "Value": value}


def r(fid, value):
    return {"Id": fid, "Type": 1, "Value": value}


def write(kind, oid, data):
    with open(os.path.join(MAP, kind, oid + ".json"), "w", encoding="utf-8", newline="\n") as f:
        f.write(json.dumps(data, indent=2, ensure_ascii=False))


# id, title, proper name, skills, model ("" = the stock death knight), tint (r, g, b), scale, story
HEROES = [
    ("UZe1", "Frost Knight of the Ebon Blade", "Thassarian", "AUfn,AUfu,AUdc,AUdd,Aamk", "", (170, 210, 255), 1.0,
     "The first death knight of Acherus to break the Lich King's hold. Frost: Frost Nova, Frost Armor, Death Coil; "
     "ultimate Death and Decay."),
    ("UZe2", "Unholy Knight of the Ebon Blade", "Koltira Deathweaver", "AUcb,AUan,AUdp,AUls,Aamk", "", (140, 255, 140),
     1.0, "A blood elf ranger raised by the Scourge, now its bane. Unholy: Carrion Beetles, Animate Dead, Death Pact; "
          "ultimate Locust Swarm."),
    ("UZe3", "Blood Knight of the Ebon Blade", "Nazgrim", "AOcr,AOsh,AUav,AOww,Aamk",
     "war3mapImported\\DeathSeerV1_03.mdl", (255, 255, 255), 1.25,
     "A Horde general who fell and rose again. Blood: Critical Strike, Shockwave, Vampiric Aura; ultimate Bladestorm."),
    ("UZe4", "Plate Knight of the Ebon Blade", "Thoras Trollbane", "AHtb,AHtc,AOae,AHav,Aamk", "", (200, 200, 200), 1.1,
     "The last king of Stromgarde, a horseman of Acherus. Plate: Storm Bolt, Thunder Clap, Endurance Aura; ultimate "
     "Avatar."),
]


def heroes():
    for oid, title, proper, skills, model, tint, scale, story in HEROES:
        mods = [s("unam", title), s("upro", proper), s("uhab", skills), s("uabi", "AInv"), s("unsf", "(Ebon Blade)"),
                n("ugol", 100), n("ulum", 0), s("ureq", ""), s("uico", BTN + "BTNHeroDeathKnight.blp"),
                s("uawt", "Revive " + proper), s("utpr", "Revive " + proper), s("utip", "Summon " + proper),
                s("utub", story), n("uclr", tint[0]), n("uclg", tint[1]), n("uclb", tint[2]), r("usca", scale),
                s("upra", "STR")]
        if model:
            mods.append(s("umdl", model))
        write("UnitData", oid, {"OldId": "Udea", "NewId": oid, "Unk": [0], "Modifications": mods})


def acherus():
    write("UnitData", "uZe0", {"OldId": "uaod", "NewId": "uZe0", "Unk": [0], "Modifications": [
        s("unam", "Acherus: The Ebon Hold"), s("utra", "UZe1,UZe2,UZe3,UZe4"), s("unsf", "(Ebon Blade)"),
        n("ufma", 40), n("ugol", 0), n("ulum", 0), r("usca", 1.2), s("upap", "unwalkable"),
        s("utub", "The necropolis of the Knights of the Ebon Blade. Revives its death knights; it cannot be destroyed.")]})


def object_info():
    lines = ["// <auto-generated> tools/shattered-legacies/content/ebon_blade.py -- object limits of the Knights of the",
             "// Ebon Blade (a hero-only faction). Do not edit. </auto-generated>",
             "using MacroTools.Shared;", "using static MacroTools.Shared.UnitCategory;", "",
             "namespace WarcraftLegacies.Shared.ShatteredLegacies.FactionObjectLimits", "{",
             "  public static class EbonBladeObjectInfo", "  {",
             "    public static IEnumerable<ObjectInfo> GetAllObjectLimits()", "    {",
             "      yield return new(" + str(fourcc("uZe0")) + ", 1, Altar); // uZe0 Acherus: The Ebon Hold"]
    cats = ["Support", "Support", "Tank", "Tank"]
    for (oid, title, proper, *_), cat in zip(HEROES, cats):
        lines.append(f"      yield return new({fourcc(oid)}, 1, {cat}); // {oid} {proper}")
    lines += ["    }", "  }", "}", ""]
    with open(INFO, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))


def fourcc(code):
    return int.from_bytes(code.encode("latin1"), "big")


if __name__ == "__main__":
    heroes()
    acherus()
    object_info()
    print("wrote UZe1-UZe4, uZe0, EbonBladeObjectInfo.cs")
