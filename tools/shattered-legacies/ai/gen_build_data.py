"""Generate native worker menus, hall upgrade paths and building tech data.
Run at the repo root. Resolve unmodified fields against the stock WC3 object,
including explicit empty map overrides. Fork-only rawcodes are installed by AiApi.
"""
import re
from pathlib import Path
from gen_ai_data import block
import unit_scan as us

ROOT = Path(us.ROOT)
STOCK = ROOT / "src/War3Api.Object/Generated/1.36.0.20257"
FIELDS = {"ubui": "StructuresBuilt", "utra": "UnitsTrained", "ureq": "Requirements",
          "urqa": "RequirementsLevels", "uupt": "UpgradesTo"}


def generate():
    if not (Path(us.MAP) / "u00D.json").exists():
        raise FileNotFoundError("Include mapdata/WarcraftLegacies/UnitData in the checkout")
    enums = (STOCK / "Enums/UnitType.cs").read_text()
    codes = {name: int(value).to_bytes(4, "little").decode("latin1")
             for name, value in re.findall(r"^\s*(\w+) = (\d+),?", enums, re.M)}
    stock = {}
    loader = (STOCK / "UnitLoader.cs").read_text()
    for name, body in re.findall(r"var unit = new Unit\(UnitType\.(\w+), db\);(.*?)return unit;", loader, re.S):
        stock[codes[name]] = {key: val.group(1) for key, prop in FIELDS.items()
                              if (val := re.search(r'unit\.Techtree' + prop + r'Raw = "(.*?)";', body))}
        texture = re.search(r'unit.PathingPathingMapRaw = "(.*?)";', body)
        if texture:
            stock[codes[name]]["upat"] = texture.group(1)
    assert "hpea" in stock and stock["hpea"]["ubui"]
    objects = {}
    for code in sorted(set(stock) | {p.stem for p in Path(us.MAP).glob("*.json")}):
        data = us.udata(code)
        objects[code] = dict(stock.get(data.get("_base") or code, {}), **data)

    def ids(code, field):
        return [v for v in str(objects.get(code, {}).get(field, "")).split(",") if len(v) == 4]

    menus = {c: ids(c, "ubui") for c in objects if ids(c, "ubui")}
    buildings = {b for menu in menus.values() for b in menu}
    # Include all morph tiers, including halls acquired already upgraded.
    pending = list(buildings)
    while pending:
        for b in ids(pending.pop(), "uupt"):
            if b not in buildings:
                buildings.add(b)
                pending.append(b)
    tables = {"Menus": menus}
    for name, field in (("Products", "utra"), ("Upgrades", "uupt"), ("Required", "ureq")):
        tables[name] = {c: ids(c, field) for c in sorted(buildings) if ids(c, field)}
    levels = {}
    for c, reqs in tables["Required"].items():
        amounts = str(objects.get(c, {}).get("urqa", "")).split(",")
        for i, req in enumerate(reqs):
            level = int(amounts[i]) if i < len(amounts) and amounts[i].isdigit() else 1
            levels.setdefault(c, []).extend([req] * max(1, level))
    tables["Required"] = levels
    # A pathing cell is 32 world units. Standard square textures encode their
    # dimensions in the filename. Named or irregular masks use the runtime fallback.
    half = {}
    for c, data in objects.items():
        size = re.search(r"(\d+)x(\d+)simple(?:solid)?\.tga$", str(data.get("upat", "")), re.I)
        if size and size[1] == size[2] and int(size[1]) != 6:
            half[c] = int(size[1]) * 16
    for fork in (False, True):
        ns = "ShatteredLegacies.Bot" if fork else "Ai"
        cls = "SlBuildData" if fork else "AiBuildData"
        blocks = []
        for name, rows in tables.items():
            base = {k: [v for v in vs if v[1] != "Z"] for k, vs in rows.items() if k[1] != "Z"}
            data = {k: vs for k, vs in rows.items() if vs != base.get(k)} if fork else base
            blocks.append(block(name, name + " from effective object data", {k:v for k,v in data.items() if v}))
        sizes = [f"      {{ {int.from_bytes(c.encode('latin1'), 'big')}, {size} }}, // {c}"
                 for c, size in sorted(half.items()) if (c[1] == "Z") == fork]
        blocks.append("    internal static readonly Dictionary<int, int> HalfWidth = new()\n    {\n"
                      + "\n".join(sizes) + "\n    };")
        path = ROOT / "src/WarcraftLegacies.Source" / ns.replace(".", "/") / (cls + ".g.cs")
        path.write_text("// Generated by tools/shattered-legacies/ai/gen_build_data.py\nusing System.Collections.Generic;\n\nnamespace WarcraftLegacies.Source." + ns + "\n{\n  internal static class " + cls + "\n  {\n" + "\n\n".join(blocks) + "\n  }\n}\n")
    return tables


if __name__ == "__main__":
    generate()
