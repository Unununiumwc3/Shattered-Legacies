"""Which units and heroes can each faction train -- and which of them does the bot AI actually train?
Reads WL's source data only (no game needed):
  src/WarcraftLegacies.Shared/FactionObjectLimits/*ObjectInfo.cs   per faction: object, limit, categories
  src/WarcraftLegacies.Shared/Units.g.cs                           UNIT_ constant -> type id
  mapdata/WarcraftLegacies/UnitData/<id>.json                       buildings: "utra" (trains), "ubui" (builds)
  src/WarcraftLegacies.Source/Ai/AiConfig.cs                        AiConfig.Heroes (the AI's hero lists)
and checks the AI's production rule (since 0.38): every building trains from its REAL train list
(AiData.Trains, generated by gen_ai_data.py), heroes come from every altar of the faction (AiConfig.Heroes only
sets the priority). Builders and ships are left out on purpose. Requirements are checked at runtime.

  python3 tools/ai/unit_scan.py            report for every faction
  python3 tools/ai/unit_scan.py Scourge    one faction
  python3 tools/ai/unit_scan.py --summary  one line per faction
Run from the repo root."""
import glob, json, os, re, struct, sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
SRC = os.path.join(ROOT, "src")
MAP = os.path.join(ROOT, "mapdata", "WarcraftLegacies", "UnitData")

AI_BUILDING = {"Barracks": ("Fighter", "Marksman"), "SiegeWorkshop": ("Siege", "Tank", "Destroyer"),
               "Magic": ("Support",), "FlyingBuilding": ("Flyer",)}
POOL_OF = {c: b for b, cats in AI_BUILDING.items() for c in cats}


def code(v):
    return struct.pack(">I", v).decode("latin1")


def load_consts():
    consts = {}
    for f in glob.glob(os.path.join(SRC, "WarcraftLegacies.Shared", "*.g.cs")):
        for name, val in re.findall(r"public const int (\w+) = (-?\d+);", open(f, encoding="utf-8-sig").read()):
            consts[name] = int(val)
    return consts


def faction_names():
    """ObjectInfo class -> faction name, via the faction class that calls ProcessObjectInfo(X.GetAllObjectLimits())."""
    out = {}
    for f in glob.glob(os.path.join(SRC, "WarcraftLegacies.Source", "Factions", "*", "*Faction.cs")):
        s = open(f, encoding="utf-8-sig").read()
        m = re.search(r"ProcessObjectInfo\((\w+)\.GetAll\w+", s)
        n = re.search(r':\s*base\(\s*"([^"]+)"', s) or re.search(r'base\(\s*"([^"]+)"', s)
        if m and n:
            out[m.group(1)] = n.group(1)
    return out


def object_infos(consts):
    names = faction_names()
    res = {}
    for f in glob.glob(os.path.join(SRC, "WarcraftLegacies.Shared", "FactionObjectLimits", "*ObjectInfo.cs")):
        s = open(f, encoding="utf-8-sig").read()
        cls = re.search(r"class (\w+ObjectInfo)", s).group(1)
        fac = names.get(cls, cls.replace("ObjectInfo", ""))
        items = []
        for args in re.findall(r"yield return new\((.*?)\);", s, re.S):
            parts = [p.strip() for p in re.split(r",(?![^<]*>)(?![^{]*})", args, maxsplit=2)]
            const = parts[0]
            if const not in consts:
                continue
            cats = re.findall(r"\b(TownHall|Keep|Castle|GilneasManor|Shipyard|Lighthouse|Farm|Altar|Specialist|"
                              r"SiegeWorkshop|Barracks|Research|Magic|Tower|Shop|Teleport|FlyingBuilding|Builder|"
                              r"Elite|Support|Marksman|Fighter|Flyer|Siege|Destroyer|Tank|Assassin|Summoner|AntiMage|"
                              r"AntiAir|Unique|Scout)\b", parts[2] if len(parts) > 2 else "")
            items.append((const, consts[const], cats))
        res[fac] = items
    return res


_udata = {}


def udata(c):
    if c not in _udata:
        f = os.path.join(MAP, c + ".json")
        m = {}
        if os.path.exists(f):
            d = json.load(open(f, encoding="utf-8-sig"))
            m = {x["Id"]: x.get("Value") for x in d["Modifications"]}
            m["_base"] = d.get("OldId")
        _udata[c] = m
    return _udata[c]


# WC3 default train lists of vanilla buildings that WL uses UNMODIFIED (no "utra" in the map data).
VANILLA_TRAINS = {
    "eaom": ["earc", "esen", "ebal"],   # Ancient of War: Archer, Huntress, Glaive Thrower
    "eaoe": ["edry", "edoc", "emtg"],   # Ancient of Lore: Dryad, Druid of the Claw, Mountain Giant
    "eaow": ["ehip", "edot", "efdr"],   # Ancient of Wind: Hippogryph, Druid of the Talon, Faerie Dragon
    "usep": ["ugho", "ucry", "ugar"],   # Crypt: Ghoul, Crypt Fiend, Gargoyle
}


def trains(c):
    v = udata(c).get("utra")
    if isinstance(v, str) and v.strip():
        return [x.strip() for x in v.split(",")]
    base = udata(c).get("_base") or c
    return VANILLA_TRAINS.get(c) or VANILLA_TRAINS.get(base)


def name_of(c, const):
    n = udata(c).get("unam")
    return n if n else const.split("_", 2)[-1].replace("_", " ").title()


def ai_heroes(consts):
    s = open(os.path.join(SRC, "WarcraftLegacies.Source", "Ai", "AiConfig.cs"), encoding="utf-8-sig").read()
    blk = s[s.index("Dictionary<string, List<int>> Heroes"):]
    blk = blk[:blk.index("\n  };")]
    out = {}
    for fac, body in re.findall(r'\{\s*"([^"]+)",\s*new List<int>\s*\{([^}]*)\}', blk):
        out[fac] = {code(consts[c.strip()]) for c in body.split(",") if c.strip() in consts}
    return out


NAVAL_BASES = {"hdes", "hbsh", "hbot", "ubot", "etrs", "obot", "nbot", "ndes", "nbsh"}  # WC3 ship base types


def is_research(c):
    return c[0] in "RZ" or os.path.exists(os.path.join(ROOT, "mapdata", "WarcraftLegacies", "UpgradeData", c + ".json"))


def is_ship(c):
    return (udata(c).get("_base") or c) in NAVAL_BASES


def is_hero(c):
    return c[0] in "HOENU"  # WC3 hero ids start with a capital H/O/E/N/U (Z/R... are researches)


def quest_unlocks(consts):
    """research code -> (quest title, faction folder) for every 'ResearchId = UPGRADE_...' in a quest class."""
    out = {}
    for f in glob.glob(os.path.join(SRC, "WarcraftLegacies.Source", "**", "Quests", "*.cs"), recursive=True):
        s = open(f, encoding="utf-8-sig").read()
        t = re.search(r'base\(\s*"([^"]+)"', s)
        for r in re.findall(r"ResearchId\s*=\s*(UPGRADE_\w+)", s):
            if r in consts and t:
                out[code(consts[r])] = (t.group(1), os.path.basename(os.path.dirname(os.path.dirname(f))))
    return out


def ai_quest_titles():
    """quest titles the AI completes or drives (EarlyQuests, QuestRules, HeroVisits, QuestUpgrades comments)."""
    s = open(os.path.join(SRC, "WarcraftLegacies.Source", "Ai", "AiConfig.cs"), encoding="utf-8-sig").read()
    t = set(re.findall(r'new (?:EarlyQuest|QuestRule|HeroVisit)\(\s*"([^"]+)"', s))
    t |= set(re.findall(r'new QuestRule\(\s*"[^"]+",\s*"([^"]+)"', s))
    t |= set(re.findall(r'new HeroVisit\(\s*"([^"]+)"', s))
    return t


def requirements(c, unlocks, ai_titles):
    v = udata(c).get("ureq")
    if not isinstance(v, str) or not v.strip():
        return ""
    parts = []
    for r in [x.strip() for x in v.split(",") if x.strip()]:
        if r in unlocks:
            title, fac = unlocks[r]
            parts.append(f'quest "{title}" ({fac}){" [AI: driven]" if title in ai_titles else " [AI: not driven]"}')
        elif r[0] in "Rr":
            parts.append(f"research {r}")
        else:
            parts.append(f"needs {r}")
    return " | requires " + "; ".join(parts)


def scan(fac, items, heroes_ai):
    buildings = [(code(v), cats) for _, v, cats in items if (code(v) in VANILLA_TRAINS or (udata(code(v)).get("_base") or "") in VANILLA_TRAINS) or cats and cats[0] in (
        "TownHall", "Keep", "Castle", "GilneasManor", "Shipyard", "Altar", "Specialist", "SiegeWorkshop", "Barracks",
        "Research", "Magic", "Tower", "Shop", "Teleport", "FlyingBuilding")]
    trainer = {}  # unit code -> [(building code, building first category)]
    unknown_lists = []
    for b, cats in buildings:
        t = trains(b)
        if t is None:
            unknown_lists.append(b)
            continue
        for u in t:
            trainer.setdefault(u, []).append((b, cats[0]))
    rows = []
    for const, v, cats in items:
        c = code(v)
        if is_research(c) or c in VANILLA_TRAINS or (udata(c).get("_base") or "") in VANILLA_TRAINS or (cats and cats[0] in ("TownHall", "Keep", "Castle", "GilneasManor", "Shipyard", "Lighthouse",
                                                  "Farm", "Altar", "Specialist", "SiegeWorkshop", "Barracks", "Research",
                                                  "Magic", "Tower", "Shop", "Teleport", "FlyingBuilding")):
            continue  # researches and buildings
        if not cats and c[0] in "hoenu" and not trainer.get(c):
            continue  # uncategorised ships etc. without a trainer of this faction
        where = trainer.get(c, [])
        hero = is_hero(c)
        if hero:
            ok = any(cat == "Altar" for _, cat in where)
            why = "altar: " + ", ".join(name_of(b, b) for b, cat in where if cat == "Altar") if ok else \
                "no altar of this faction trains it (quest/summon hero)"
            if c in heroes_ai.get(fac, set()):
                why += " (priority list)"
        else:
            first = cats[0] if cats else None
            if is_ship(c):
                ok, why = False, "ship (WC3 naval base type) -> left out"
            elif first is None:
                ok, why = False, "no category, not a ship (e.g. a building like a Demon Gate) -> left out"
            elif first == "Builder":
                ok, why = False, "builder -> left out"
            elif where:
                ok, why = True, "trained at " + ", ".join(f"{name_of(b, b)} ({cat})" for b, cat in where)
            else:
                ok, why = False, "no building of this faction trains it (quest/summon unit)"
        rows.append((ok, hero, c, name_of(c, const), why + requirements(c, UNLOCKS, AI_TITLES)))
    return rows, unknown_lists


UNLOCKS = {}
AI_TITLES = set()


def markdown(infos, heroes_ai):
    """--md: one table per faction for fallback decisions (ships and builders left out)."""
    out = ["# Units and heroes per faction", "",
           "Generated by `python3 tools/ai/unit_scan.py --md` from WL's data. For the fallback decisions: mark per row",
           "**keep** / **lose** in the last column. Ships and builders are left out. \"Trained at\" = the building that",
           "trains it (heroes: the altar).", ""]
    for fac in sorted(infos):
        rows, _ = scan(fac, infos[fac], heroes_ai)
        rows = [r for r in rows if "ship" not in r[4] and "builder" not in r[4] and "no category" not in r[4]]
        if not rows:
            continue
        out += [f"## {fac}", "", "| Kind | Name | Code | Trained at / note | Fallback |", "|---|---|---|---|---|"]
        for ok, hero, c, n, why in sorted(rows, key=lambda r: (not r[1], r[4], r[3])):
            where = why.split(" | requires ")[0].replace("trained at ", "").replace("altar: ", "")
            if " (priority list)" in where:
                where = where.replace(" (priority list)", "")
            req = (" -- needs " + why.split(" | requires ")[1]) if " | requires " in why else ""
            out.append(f"| {'hero' if hero else 'unit'} | {n} | `{c}` | {where}{req} | |")
        out.append("")
    return "\n".join(out)


def main(a):
    consts = load_consts()
    UNLOCKS.update(quest_unlocks(consts))
    AI_TITLES.update(ai_quest_titles())
    infos = object_infos(consts)
    heroes_ai = ai_heroes(consts)
    if "--md" in a:
        print(markdown(infos, heroes_ai))
        return
    only = [x for x in a if not x.startswith("--")]
    summary = "--summary" in a
    tot_u = tot_ok = tot_h = tot_hok = 0
    for fac in sorted(infos):
        if only and fac not in only:
            continue
        rows, unknown = scan(fac, infos[fac], heroes_ai)
        units = [r for r in rows if not r[1]]
        heroes = [r for r in rows if r[1]]
        uok = sum(1 for r in units if r[0])
        hok = sum(1 for r in heroes if r[0])
        tot_u += len(units); tot_ok += uok; tot_h += len(heroes); tot_hok += hok
        if summary:
            print(f"{fac:16} units {uok:2}/{len(units):2}   heroes {hok}/{len(heroes)}")
            continue
        print(f"\n=== {fac}: AI trains {uok}/{len(units)} units, {hok}/{len(heroes)} heroes")
        for ok, hero, c, n, why in sorted(rows, key=lambda r: (r[1], r[0], r[3])):
            print(f"  {'OK ' if ok else '-- '}{'H ' if hero else '  '}{c} {n:34} {why}")
        if unknown:
            print("  (buildings without a train list in the map data, vanilla defaults: " + ", ".join(unknown) + ")")
    print(f"\nALL: AI trains {tot_ok}/{tot_u} unit types and {tot_hok}/{tot_h} hero types")


if __name__ == "__main__":
    main(sys.argv[1:])
